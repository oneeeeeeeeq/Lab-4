def area(a, h):
    '''
    Возвращает площадь треугольника по длине его основания и высоты к нему.

            Параметры:
                    a (float): Длина основания треугольника
                    h (int): Длина высоты треугольника, опущенной на основание

            Возвращаемое значение:
                    triangle_area (float): площадь треугольника с основанием, равным a, и высотой к основанию, равной h
            
            Пример вызова функции:
            area(9, 3)
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''
    Возвращает периметр треугольника по длинам всх его сторон.

            Параметры:
                    a (int): Длина основания треугольника
                    h (int): Длина высоты треугольника, опущенной на основание

            Возвращаемое значение:
                    triangle_area (int): площадь треугольника с основанием, равным a, и высотой к основанию, равной h
            
            Пример вызова функции:
            area(9, 3)
    '''
    return a + b + c
