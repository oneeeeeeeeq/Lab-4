def area(a, h):
    '''
    Возвращает площадь треугольника по длине его основания и высоты к нему.

            Параметры:
                    a (float): Длина основания треугольника
                    h (float): Длина высоты треугольника, опущенной на основание

            Возвращаемое значение:
                    triangle_area (float): площадь треугольника с основанием, равным a, и высотой к основанию, равной h
            
            Пример вызова функции:
            area(9, 3)
    '''
    return a * h / 2

def perimeter(a, b, c):
    '''
    Возвращает периметр треугольника по длинам всх его сторон.

            Параметры:
                    a (float): Длина первой стороны треугольника
                    b (float): Длина второй стороны треугольника
                    c (float): Длина третьей стороны треугольника

            Возвращаемое значение:
                    triangle_perimeter (float): периметр треугольника со сторонами a, b, c
            
            Пример вызова функции:
            permeter(4, 3, 5)
    '''
    return a + b + c
