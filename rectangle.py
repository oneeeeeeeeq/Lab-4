def rectangle_area(a, b):
    '''
    Возвращает площадь прямоугольника по длинам его смежных сторон.

            Параметры:
                    a (float): Длина прямоугольника
                    b (float): Ширина прямоугольника

            Возвращаемое значение:
                    rectangle_area (float): площадь прямоугольника с длиной a и шириной b
            
            Пример вызова функции:
            area(5, 7)
    '''
    return a * b

def rectangle_perimeter(a, b):
    '''
    Возвращает периметр прямоугольника по длинам его смежных сторон.

            Параметры:
                    a (float): Длина прямоугольника
                    b (float): Ширина прямоугольника

            Возвращаемое значение:
                    rectangle_perimeter (float): периметр прямоугольника с длиной a и шириной b
            
            Пример вызова функции:
            perimeter(4, 19)
    '''
    return 2 * (a + b)