import math


def circle_area(r):
    '''
    Возвращает площадь круга по длине его радиуса.

            Параметры:
                    r (float): радиус окружности

            Возвращаемое значение:
                    circle_area (float): площадь круга с радиусом r
            
            Пример вызова функции:
            area(9)
    '''
    return math.pi * r * r


def circle_perimeter(r):
    '''
    Возвращает длину окуржности по длине ее радиуса.

            Параметры:
                    r (float): радиус окружности

            Возвращаемое значение:
                    circle_perimeter (float): длина окружности радиусом r
            
            Пример вызова функции:
            perimeter(8)
    '''
    return 2 * math.pi * r

